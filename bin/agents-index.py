#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = ["pyyaml"]
# ///
"""Build (or check) index.yaml — the tree's catalog of what it ships and who it is for.

The index exists so a *client* can select a subset without reading every file:
a harness that cannot use Claude-only skills, or a machine that must not see
homelab ones. It is generated from the frontmatter, never hand-edited, so the
skill file stays the single source of truth.

Selection vocabulary (both optional, both in SKILL.md / <command>.md frontmatter):

    harness: [claude]        # applicability — omit to mean "every harness"
    tags: [homelab]          # context tags — a client may exclude by tag

Usage (uv resolves pyyaml from the inline metadata above):
    uv run --script bin/agents-index.py --write     # regenerate index.yaml
    uv run --script bin/agents-index.py --check     # exit 1 if index.yaml is stale
    uv run --script bin/agents-index.py --select --harness pi --exclude-tag homelab
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

TREE = Path(__file__).resolve().parent.parent
INDEX = TREE / "index.yaml"
HARNESSES = ["claude", "pi", "dsh"]

HEADER = """# GENERATED by bin/agents-index.py — do not hand-edit.
# Source of truth is the frontmatter of each SKILL.md / command file.
#
#   harness: omitted means every harness. tags: are for client-side exclusion
#   (e.g. a work machine excludes `homelab`). Regenerate with:
#       bin/agents-index.py --write
"""


def parse_frontmatter(text: str) -> dict:
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end == -1:
        return {}
    data = yaml.safe_load(text[4:end])
    return data if isinstance(data, dict) else {}


def entry(path: Path, kind: str) -> dict | None:
    fm = parse_frontmatter(path.read_text())
    name = fm.get("name") or (path.parent.name if kind == "skill" else path.stem)
    description = (fm.get("description") or "").strip()
    if not description:
        return None
    harness = fm.get("harness") or HARNESSES
    if isinstance(harness, str):
        harness = [harness]
    tags = fm.get("tags") or []
    if isinstance(tags, str):
        tags = [tags]
    return {
        "name": name,
        "kind": kind,
        "path": str(path.relative_to(TREE)),
        "harness": sorted(harness),
        "tags": sorted(tags),
        # Kept short: the index is for selection, not for reading the skill.
        "summary": description.split(". ")[0].rstrip(".") + ".",
    }


def collect() -> list[dict]:
    out = []
    for skill in sorted((TREE / "skills").glob("*/SKILL.md")):
        if e := entry(skill, "skill"):
            out.append(e)
    for cmd in sorted((TREE / "commands").glob("*.md")):
        if e := entry(cmd, "command"):
            out.append(e)
    return out


def render(entries: list[dict]) -> str:
    return HEADER + yaml.safe_dump(
        {"entries": entries}, sort_keys=False, allow_unicode=True, width=100
    )


def select(
    entries: list[dict], harness: str | None, exclude_tags: set[str]
) -> list[dict]:
    """Everything the named client should see. Absent harness ⇒ every harness."""
    out = []
    for e in entries:
        if harness and harness not in e["harness"]:
            continue
        if exclude_tags & set(e["tags"]):
            continue
        out.append(e)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate index.yaml")
    mode.add_argument(
        "--check", action="store_true", help="exit 1 if index.yaml is stale"
    )
    mode.add_argument(
        "--select", action="store_true", help="print the names a client should see"
    )
    ap.add_argument("--harness", choices=HARNESSES, help="filter to one harness")
    ap.add_argument("--exclude-tag", action="append", default=[], metavar="TAG")
    ap.add_argument("--kind", choices=["skill", "command"], help="filter to one kind")
    args = ap.parse_args()

    entries = collect()

    if args.write:
        INDEX.write_text(render(entries))
        print(f"wrote {INDEX.relative_to(TREE)} ({len(entries)} entries)")
        return 0

    if args.check:
        current = INDEX.read_text() if INDEX.exists() else ""
        if current != render(entries):
            print(
                "index.yaml is stale — run: bin/agents-index.py --write",
                file=sys.stderr,
            )
            return 1
        print(f"index.yaml current ({len(entries)} entries)")
        return 0

    chosen = select(entries, args.harness, set(args.exclude_tag))
    for e in chosen:
        if args.kind and e["kind"] != args.kind:
            continue
        print(e["name"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
