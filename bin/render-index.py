#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = ["pyyaml"]
# ///
"""Build (or check) modules/index.yaml — the catalog of what the marketplace ships and who it is for.

Generated from each module's manifests and skill frontmatter, never hand-edited.
A client (a fleet bootstrap, a harness that cannot use Claude-only skills, a
machine that must not see `homelab` content) selects a subset from this file
instead of reading every module.

    uv run --script bin/render-index.py --write
    uv run --script bin/render-index.py --check     # exit 1 if stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MODULES = ROOT / "modules"
INDEX = MODULES / "index.yaml"
HARNESSES = ["claude", "pi", "dsh"]

HEADER = """# GENERATED by bin/render-index.py — do not hand-edit.
# Source of truth: each module's package.json / plugin.json and the frontmatter
# of its SKILL.md files. `harness` omitted on a skill means every harness;
# `tags` are for client-side exclusion. Regenerate: bin/render-index.py --write
"""


def frontmatter(text: str) -> dict:
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    data = yaml.safe_load(text[4:end]) if end != -1 else None
    return data if isinstance(data, dict) else {}


def as_list(v) -> list:
    return [v] if isinstance(v, str) else list(v or [])


def module_entry(mod: Path) -> dict:
    pkg = json.loads((mod / "package.json").read_text()) if (mod / "package.json").exists() else {}
    plugin = mod / ".claude-plugin" / "plugin.json"
    kinds = []
    if (mod / "skills").is_dir():
        kinds.append("skills")
    if (mod / "extensions").is_dir():
        kinds.append("pi-extension")
    if "dsh" in pkg:
        kinds.append("dsh-plugin")
    if (mod / "hooks" / "hooks.json").exists():
        kinds.append("hooks")
    harness = []
    if plugin.exists():
        harness.append("claude")
    if (mod / "skills").is_dir() or "pi" in pkg:
        harness.append("pi")
    if (mod / "skills").is_dir() or "dsh" in pkg:
        harness.append("dsh")
    skills = []
    for skill in sorted(mod.glob("skills/*/SKILL.md")):
        fm = frontmatter(skill.read_text())
        desc = (fm.get("description") or "").strip()
        skills.append({
            "name": fm.get("name") or skill.parent.name,
            "path": str(skill.relative_to(ROOT)),
            "harness": sorted(as_list(fm.get("harness")) or HARNESSES),
            "tags": sorted(as_list(fm.get("tags"))),
            "command": bool(fm.get("user-invocable")),
            "summary": desc.split(". ")[0].rstrip(".") + "." if desc else "",
        })
    # A skills module is only usable on a harness some skill allows.
    if skills:
        allowed = set().union(*(set(s["harness"]) for s in skills))
        harness = [h for h in harness if h in allowed or h == "claude" and plugin.exists()]
    return {
        "name": mod.name,
        "version": pkg.get("version", ""),
        "kinds": kinds,
        "harness": sorted(set(harness), key=HARNESSES.index),
        "description": pkg.get("description", ""),
        "skills": skills,
    }


def render() -> str:
    entries = [module_entry(m) for m in sorted(MODULES.iterdir()) if m.is_dir() and (m / "package.json").exists()]
    return HEADER + yaml.safe_dump({"modules": entries}, sort_keys=False, allow_unicode=True, width=100)


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.write:
        INDEX.write_text(text)
        print(f"wrote {INDEX.relative_to(ROOT)}")
        return 0
    if not INDEX.exists() or INDEX.read_text() != text:
        print(f"  FAIL {INDEX.relative_to(ROOT)} is stale — run bin/render-index.py --write")
        return 1
    print("  ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
